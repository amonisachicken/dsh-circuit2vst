/**
 * Parameter consistency between the manifest and the generated circuit.
 *
 * A plugin can build successfully while its knobs do nothing: the manifest
 * declares parameters, the circuit implements its own `Params` struct, and
 * nothing compares the two. (This is not hypothetical — a canvas-drawn circuit
 * with no potentiometers generates `pub struct Params;`, while the panel still
 * offers four controls.)
 *
 * This module reads both sides and reports the mismatches:
 *
 * - params that map to a circuit field (`circuit = "x"`) while the circuit has
 *   neither that field nor a `params_builder` to receive it;
 * - circuit params that no `[[params]]` exposes (so no control can change them);
 * - `[[ui.*]]` controls bound to a param that was never declared;
 * - a circuit without `IN` / `OUT` ports.
 *
 * Everything is read-only; a missing circuit is a warning, not an error.
 */
import { existsSync } from 'node:fs'
import { readdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'

/**
 * Parse `[[params]]` and every `[[ui.*]]` block of a manifest.
 *
 * A tiny purpose-built TOML reader: only the few keys this check needs are
 * extracted, so no dependency is required.
 *
 * @param projectDir - project root.
 * @returns `{params, controls, circuit}` — `circuit` holds `[circuit]` keys such
 *   as `params_builder`, which decides whether a mapped field must exist as a
 *   struct field or is passed as a positional builder argument.
 */
export async function readManifest(projectDir) {
  const text = await readFile(join(projectDir, 'rustomp.toml'), 'utf8')
  const params = []
  const controls = []
  const circuit = {}
  let current = null
  let section = ''
  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim()
    const table = /^\[\[([^\]]+)\]\]$/.exec(line)
    if (table !== null) {
      section = table[1]
      current = { section }
      if (section === 'params') params.push(current)
      else if (section.startsWith('ui.')) controls.push(current)
      continue
    }
    const single = /^\[([^\]]+)\]$/.exec(line)
    if (single !== null) { section = single[1]; current = null; continue }
    const pair = /^([A-Za-z0-9_]+)\s*=\s*(.+)$/.exec(line)
    if (pair === null) continue
    const key = pair[1]
    let value = pair[2].trim()
    if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1)
    if (section === 'circuit') { circuit[key] = value; continue }
    if (current === null) continue
    if (key === 'id' || key === 'circuit' || key === 'param') current[key] = value
  }
  return { params, controls, circuit }
}

/**
 * Read the parameter fields and ports from the circuit crate.
 *
 * Scans the whole `circuit/src` tree, not just `generated/`: branch projects put
 * `Params` in their branch modules, while hand-written helper functions (such as
 * `make_params`) and alternative layouts live next to them in `lib.rs`.
 *
 * @param projectDir - project root.
 * @returns `{exists, fields, functions, hasIn, hasOut, files}`.
 */
export async function readCircuitParams(projectDir) {
  const root = join(projectDir, 'circuit', 'src')
  if (!existsSync(root)) return { exists: false, fields: [], functions: [], hasIn: false, hasOut: false, files: [] }
  const files = []
  const walk = async (dir) => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name)
      if (entry.isDirectory()) await walk(full)
      else if (entry.name.endsWith('.rs')) files.push(full)
    }
  }
  await walk(root)
  if (files.length === 0) return { exists: false, fields: [], functions: [], hasIn: false, hasOut: false, files: [] }
  const fields = new Set()
  const functions = new Set()
  let generated = false
  let hasIn = false
  let hasOut = false
  for (const file of files) {
    const text = await readFile(file, 'utf8')
    for (const match of text.matchAll(/pub\s+fn\s+([A-Za-z_][A-Za-z0-9_]*)/g)) functions.add(match[1])
    if (/pub\s+struct\s+Params\s*\{/.test(text)) {
      const block = /pub\s+struct\s+Params\s*\{([\s\S]*?)\}/.exec(text)
      if (block !== null) {
        for (const match of block[1].matchAll(/pub\s+([A-Za-z_][A-Za-z0-9_]*)\s*:/g)) fields.add(match[1])
      }
    }
    if (/@generated by rustomp-import/.test(text) || /pub\s+const\s+UNKNOWNS\s*:/.test(text)) generated = true
    if (/pub\s+const\s+IN\s*:/.test(text)) hasIn = true
    if (/pub\s+const\s+OUT\s*:/.test(text)) hasOut = true
  }
  return {
    exists: true,
    fields: [...fields],
    functions: [...functions],
    generated,
    hasIn,
    hasOut,
    files: files.map((file) => file.slice(root.length + 1)),
  }
}

/** Indicator ids the panel designer may bind an LED to without declaring a param. */
const VIRTUAL_INDICATORS = new Set(['clip_indicator'])

/**
 * Compare the manifest with the generated circuit.
 * @param projectDir - project root.
 * @returns `{ok, issues, params, circuit}`.
 */
export async function checkParams(projectDir) {
  const manifest = await readManifest(projectDir)
  const circuit = await readCircuitParams(projectDir)
  const issues = []

  if (!circuit.exists) {
    issues.push({
      level: 'warn',
      code: 'no-circuit',
      msg: '还没有生成电路代码（先点「生成代码」）',
    })
  } else {
    // Hand-written circuits (a `Circuit` impl) do not need these consts; only a
    // netlist-generated circuit must expose the IN/OUT nodes.
    if (circuit.generated && !circuit.hasIn) issues.push({ level: 'error', code: 'no-in', msg: '电路没有 IN 端口（网表里缺 * @rustomp in=…）' })
    if (circuit.generated && !circuit.hasOut) issues.push({ level: 'error', code: 'no-out', msg: '电路没有 OUT 端口（网表里缺 * @rustomp out=…）' })
  }

  const declared = manifest.params.filter((param) => typeof param.id === 'string' && param.id !== '')
  const circuitFields = new Set(circuit.fields)
  const builder = typeof manifest.circuit.params_builder === 'string' ? manifest.circuit.params_builder : ''
  const builderExists = builder !== '' && circuit.functions.includes(builder)
  // Only params with an explicit `circuit = "field"` reach the circuit; a param
  // without it is plugin-level (bypass, expression, branch selector, …).
  const mapped = declared.filter((param) => typeof param.circuit === 'string' && param.circuit !== '')

  if (circuit.exists && builder !== '' && !builderExists) {
    issues.push({
      level: 'warn',
      code: 'builder-missing',
      msg: `rustomp.toml 声明 params_builder = "${builder}"，但生成的电路里没有这个函数 —— 参数可能传不进电路`,
    })
  }
  if (circuit.exists) {
    for (const param of mapped) {
      if (circuitFields.has(param.circuit)) continue
      // A positional builder receives the values as arguments, so a missing
      // struct field is expected in register-accumulator style circuits.
      if (builderExists) continue
      issues.push({
        level: 'warn',
        code: 'param-not-in-circuit',
        msg: `参数 ${param.id} 映射到电路字段 ${param.circuit}，但电路既没有该字段也没有 ${builder === '' ? 'params_builder' : builder} —— 这个控件不会影响声音`,
      })
    }
    const exposed = new Set(mapped.map((param) => param.circuit))
    for (const field of circuitFields) {
      if (!exposed.has(field)) {
        issues.push({
          level: 'warn',
          code: 'param-not-exposed',
          msg: `电路的参数 ${field} 没有对应的 [[params]]（circuit = "${field}"），界面无法调节它`,
        })
      }
    }
  }

  const paramIds = new Set(declared.map((param) => param.id))
  for (const control of manifest.controls) {
    const bound = control.param
    if (typeof bound !== 'string' || bound === '') continue
    if (VIRTUAL_INDICATORS.has(bound)) continue
    if (!paramIds.has(bound)) {
      issues.push({
        level: 'warn',
        code: 'ui-unknown-param',
        msg: `${control.section}${control.id === undefined ? '' : ` ${control.id}`} 绑定到不存在的参数 ${bound}`,
      })
    }
  }

  return {
    ok: issues.every((issue) => issue.level !== 'error'),
    issues,
    // Only params with an explicit circuit mapping are compared with the circuit.
    params: mapped.map((param) => ({ id: param.id, field: param.circuit })),
    circuit,
  }
}

/**
 * Human-readable form of a check result, appended to job logs.
 * @param report - result of `checkParams`.
 * @returns a few lines of text.
 */
export function formatParamReport(report) {
  if (report.issues.length === 0) {
    const count = report.params.length
    return `参数一致性：通过（${count} 个电路参数，电路 ${report.circuit.files.join(' / ') || '无'}）`
  }
  const lines = [`参数一致性：${report.issues.length} 项需要留意`]
  for (const issue of report.issues) lines.push(`  ${issue.level === 'error' ? '✗' : '!'} ${issue.msg}`)
  return lines.join('\n')
}
