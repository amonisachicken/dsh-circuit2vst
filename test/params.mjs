/**
 * Unit tests for the manifest ↔ circuit parameter check.
 *
 * Each case builds a throwaway project directory, so the rules are pinned without
 * depending on any real project on this machine.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { checkParams } from '../src/host/params.js'

/**
 * Create a project fixture.
 * @param files - project-relative path → contents.
 * @returns the project directory.
 */
async function fixture(files) {
  const dir = await mkdtemp(join(tmpdir(), 'c2v-params-'))
  for (const [relative, text] of Object.entries(files)) {
    const target = join(dir, relative)
    await mkdir(join(target, '..'), { recursive: true })
    await writeFile(target, text, 'utf8')
  }
  return dir
}

/** Minimal manifest with one circuit-mapped param and one plugin-only param. */
const MANIFEST = `[circuit]
params_type = "Params"

[[params]]
id = "gain"
name = "Gain"
type = "float"
circuit = "gain"

[[params]]
id = "bypass"
name = "Bypass"
type = "bool"
`

test('a mapped param that the circuit implements passes', async () => {
  const dir = await fixture({
    'rustomp.toml': MANIFEST,
    'circuit/src/generated/circuit.rs': `// @generated by rustomp-import
pub struct Params {
    pub gain: f64,
}
pub const IN: usize = 1;
pub const OUT: usize = 2;
`,
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues, [])
    assert.equal(report.ok, true)
    assert.deepEqual(report.params, [{ id: 'gain', field: 'gain' }])
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a mapped param missing from a flat circuit is reported', async () => {
  const dir = await fixture({
    'rustomp.toml': MANIFEST,
    'circuit/src/generated/circuit.rs': `// @generated by rustomp-import
pub struct Params;
pub const IN: usize = 1;
pub const OUT: usize = 2;
`,
  })
  try {
    const report = await checkParams(dir)
    const codes = report.issues.map((issue) => issue.code)
    assert.deepEqual(codes, ['param-not-in-circuit'])
    assert.equal(report.ok, true, 'a warning must not block generation')
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a params_builder receives mapped fields positionally', async () => {
  const dir = await fixture({
    'rustomp.toml': `${MANIFEST.replace('params_type = "Params"', 'params_type = "Params"\nparams_builder = "make_params"')}`,
    'circuit/src/lib.rs': 'pub fn make_params(gain: f64) -> Params { Params { gain } }\npub struct Params { pub gain: f64 }\n',
    'circuit/src/generated/circuit.rs': `// @generated by rustomp-import
pub const IN: usize = 1;
pub const OUT: usize = 2;
`,
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues, [])
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a declared builder that the circuit lacks is reported', async () => {
  const dir = await fixture({
    'rustomp.toml': `${MANIFEST.replace('params_type = "Params"', 'params_type = "Params"\nparams_builder = "make_params"')}`,
    'circuit/src/lib.rs': 'pub struct Params { pub gain: f64 }\n',
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues.map((issue) => issue.code), ['builder-missing'])
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('an LED bound to the clip indicator is not an unknown param', async () => {
  const dir = await fixture({
    'rustomp.toml': `${MANIFEST}\n[[ui.leds]]\nparam = "clip_indicator"\n`,
    'circuit/src/generated/circuit.rs': `// @generated by rustomp-import
pub struct Params { pub gain: f64 }
pub const IN: usize = 1;
pub const OUT: usize = 2;
`,
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues, [])
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a panel control bound to an unknown param is reported', async () => {
  const dir = await fixture({
    'rustomp.toml': `${MANIFEST}
[[ui.leds]]
param = "mystery_led"
`,
    'circuit/src/generated/circuit.rs': `// @generated by rustomp-import
pub struct Params { pub gain: f64 }
pub const IN: usize = 1;
pub const OUT: usize = 2;
`,
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues.map((issue) => issue.code), ['ui-unknown-param'])
    assert.match(report.issues[0].msg, /mystery_led/)
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a generated circuit without ports fails', async () => {
  const dir = await fixture({
    'rustomp.toml': MANIFEST,
    'circuit/src/generated/circuit.rs': '// @generated by rustomp-import\npub struct Params { pub gain: f64 }\n',
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues.map((issue) => issue.code), ['no-in', 'no-out'])
    assert.equal(report.ok, false, 'missing ports must block generation')
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a hand-written circuit needs no port constants', async () => {
  const dir = await fixture({
    'rustomp.toml': MANIFEST,
    'circuit/src/gain.rs': 'pub struct Params { pub gain: f64 }\nimpl Circuit for Gain {}\n',
  })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues, [])
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('a missing circuit is only a warning', async () => {
  const dir = await fixture({ 'rustomp.toml': MANIFEST })
  try {
    const report = await checkParams(dir)
    assert.deepEqual(report.issues.map((issue) => issue.code), ['no-circuit'])
    assert.equal(report.ok, true)
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})
